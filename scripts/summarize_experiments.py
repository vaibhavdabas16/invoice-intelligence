"""Summarise every evaluation run under reports/experiments/ (+ the official run in reports/).

Also computes the *actual* API spend: the sum of the cost of every call that
was really sent to the provider (cache hits are excluded, since they cost nothing).
Note: a call that was first made in one run and replayed from cache in a later
run is counted once, in the run that made it.

Usage: python scripts/summarize_experiments.py  ->  reports/experiments/summary.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.cost.pricing import cost_usd, cost_usd_without_prompt_cache  # noqa: E402
from src.extraction.providers.base import TokenUsage  # noqa: E402

REPORTS = ROOT / "reports"


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.1f}%"


def _spend(attempts: list[dict]) -> float:
    total = 0.0
    for a in attempts:
        if a.get("from_cache"):
            continue
        u = a["usage"]
        total += cost_usd(TokenUsage(**u), a["model"]) or 0.0
    return total


def _no_cache_cost(attempts: list[dict]) -> float:
    """Recomputed from raw per-call usage, so it also works for runs made before this column existed."""
    return sum(cost_usd_without_prompt_cache(TokenUsage(**a["usage"]), a["model"]) or 0.0 for a in attempts)


def main() -> int:
    runs: list[tuple[str, Path]] = []
    if (REPORTS / "eval_results.json").exists():
        runs.append(("OFFICIAL (reports/)", REPORTS / "eval_results.json"))
    runs += [(p.parent.name, p) for p in sorted((REPORTS / "experiments").glob("*/eval_results.json"))]

    lines = [
        "# Experiment summary",
        "",
        "Generated by `python scripts/summarize_experiments.py`. One row per evaluation run.",
        "",
        "| run | data | model | mode | effort | verify | field acc. | docs w/ error | items P/R"
        " | flagged (with err / without) | flag recall | avg $/doc (billed) | avg $/doc (no prompt cache) | calls |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    spend_total = 0.0
    for name, path in runs:
        r = json.loads(path.read_text(encoding="utf-8"))
        cfg, s, li, rf, c = r["config"], r["summary"], r["line_item_metrics"], r["review_flag"], r["cost"]["all"]
        docs = r["documents"]
        data = "stress_" + name.split("stress_")[1].split("_")[0] if "stress_" in name else "labelled"
        spend_total += sum(_spend(d["attempts"]) for d in docs)
        no_cache_avg = sum(_no_cache_cost(d["attempts"]) for d in docs) / len(docs)
        lines.append(
            f"| {name} | {data} | {cfg['model']} | {cfg['input_mode']} | {cfg['effort']} | "
            f"{cfg.get('verify_scans', False)} | {_pct(s['overall_field_accuracy'])} | "
            f"{s['documents_with_at_least_one_error']}/{s['documents']} | "
            f"{_pct(li['item_precision'])}/{_pct(li['item_recall'])} | "
            f"{rf['flagged_with_errors']}/{rf['flagged_without_errors']} | {_pct(rf['recall'])} | "
            f"{c['avg_cost_per_document_usd']:.6f} | {no_cache_avg:.6f} | "
            f"{c['total_api_calls']} |"
        )

    batch_spend = 0.0
    for meta in sorted((ROOT / "outputs" / "_meta").glob("*.meta.json")):
        batch_spend += _spend(json.loads(meta.read_text(encoding="utf-8"))["attempts"])
    spend_total += batch_spend

    lines += [
        "",
        f"**Actual API spend recorded across all runs above plus the 20-document batch: ${spend_total:.4f}** "
        f"(batch share: ${batch_spend:.4f}). Computed from provider-reported token usage of calls that were "
        "really sent (cache hits excluded). Excludes calls not recorded in these files (e.g. ad-hoc CLI "
        "smoke tests); the OpenAI usage dashboard is the authoritative figure.",
        "",
    ]
    out = REPORTS / "experiments" / "summary.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
