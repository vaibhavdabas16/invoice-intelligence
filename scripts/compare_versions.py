"""Before/after comparison of the v1 and v2 pipeline configurations.

v1    = prompt v1, consistency check on, no photo upscaling, image-quality warnings trigger review.
v2    = prompt v2 (+ invoice-number occurrences), photo upscaling, arithmetic arbitration,
        invoice-number cross-checks, image-quality warnings informational only.
final = v2 without the occurrences field (prompt v3 = v1 wording); text-layer grounding kept.

Every number comes from eval_results.json files written by `python -m src.eval.run`.
Multiple runs of the same configuration are listed individually and averaged.

Usage: python scripts/compare_versions.py  ->  reports/experiments/v1_vs_v2.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parent.parent
EXP = ROOT / "reports" / "experiments"

GROUPS: list[tuple[str, dict[str, list[str]]]] = [
    # dataset -> {version: runs}. "final" is the shipped configuration.
    ("labelled (clean)", {"v1": ["v1_official"], "v2": ["v2_labelled_r1", "v2_labelled_r2"], "final": ["../"]}),
    (
        "stress_mild",
        {
            "v1": ["stress_mild_verify", "stress_mild_verify_fresh1", "stress_mild_verify_fresh2"],
            "v2": ["v2_stress_mild_r1", "v2_stress_mild_r2", "v2_stress_mild_r3"],
            "final": ["final_stress_mild_r1", "final_stress_mild_r2", "final_stress_mild_r3"],
        },
    ),
    ("stress_severe", {"v1": ["stress_severe_verify"], "v2": ["v2_stress_severe"], "final": ["final_stress_severe"]}),
    ("stress_rot90", {"v1": ["e2_rot90"], "v2": ["v2_rot90"], "final": ["final_rot90"]}),
    ("stress_rot270", {"v1": ["e2_rot270"], "v2": ["v2_rot270"], "final": ["final_rot270"]}),
]


def load(run: str) -> dict:
    path = (EXP / run / "eval_results.json").resolve()
    return json.loads(path.read_text(encoding="utf-8"))


def stats(r: dict) -> dict:
    s, rf, c = r["summary"], r["review_flag"], r["cost"]["all"]
    return {
        "acc": s["overall_field_accuracy"],
        "field_errors": s["total_fields"] - s["correct_fields"],
        "docs_err": s["documents_with_at_least_one_error"],
        "flag_err": rf["flagged_with_errors"],
        "flag_ok": rf["flagged_without_errors"],
        "missed": rf["unflagged_with_errors"],
        "cost": c["avg_cost_per_document_usd"],
        "calls": c["total_api_calls"],
        "wrong": {d["document_id"]: d["wrong_fields"] for d in r["documents"] if d["wrong_fields"]},
    }


def fmt_group(runs: list[str]) -> tuple[str, dict]:
    rows = [stats(load(x)) for x in runs]
    agg = {
        k: mean(row[k] for row in rows)
        for k in ("acc", "field_errors", "docs_err", "flag_err", "flag_ok", "missed", "cost", "calls")
    }
    caught = sum(row["flag_err"] for row in rows)
    erroneous = caught + sum(row["missed"] for row in rows)
    flagged = caught + sum(row["flag_ok"] for row in rows)
    agg["recall"] = caught / erroneous if erroneous else None
    agg["precision"] = caught / flagged if flagged else None
    return "; ".join(f"{r['acc'] * 100:.1f}%" for r in rows), agg | {"per_run": rows}


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.0f}%"


def main() -> int:
    out = [
        "# v1 vs v2 vs final comparison",
        "",
        "Generated by `python scripts/compare_versions.py`. Means over the listed runs; flag precision/recall are",
        "pooled over all documents of all runs in a cell (counts are small, so read them as indicative).",
        "",
        "| dataset | version | runs | field accuracy per run | mean field errors / run | docs with error | "
        "flagged with error / without | missed errors | flag recall | flag precision | avg $/doc | calls/run |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    details = ["", "## Wrong fields per run", ""]
    for name, versions in GROUPS:
        for version, runs in versions.items():
            try:
                per_run, a = fmt_group(runs)
            except FileNotFoundError as exc:
                out.append(f"| {name} | {version} | missing: {exc.filename} |")
                continue
            out.append(
                f"| {name} | {version} | {len(runs)} | {per_run} | {a['field_errors']:.2f} | {a['docs_err']:.2f} | "
                f"{a['flag_err']:.2f} / {a['flag_ok']:.2f} | {a['missed']:.2f} | {pct(a['recall'])} | "
                f"{pct(a['precision'])} | {a['cost']:.6f} | {a['calls']:.1f} |"
            )
            for run, row in zip(runs, a["per_run"], strict=True):
                details.append(
                    f"- **{name} {version}** `{run.strip('./') or 'reports/'}`: {row['wrong'] or 'no errors'}"
                )
    text = "\n".join(out + details) + "\n"
    (EXP / "v1_vs_v2.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
